def load(p):
    return p.read_text(encoding="utf-8").split("\n")


def save(p, L):
    # 去掉末尾多余空行后统一写回（保持裸 LF）
    while L and L[-1].strip() == "":
        L.pop()
    p.write_text("\n".join(L) + "\n", encoding="utf-8", newline="\n")
    print(p.name, "→", len(L) + 1, "行")


